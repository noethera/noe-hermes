#!/usr/bin/env bash
# Build ui/dist/noethera-theme-setup.sh: ONE self-contained file that installs the Noethera (Claude-style) Hermes
# theme on any Mac/Linux machine that already has Hermes, without this repo. It embeds themes/*.yaml and
# bubbles.css as they are NOW in the working copy, so re-run this after every change to the theme.
set -euo pipefail
UI="$(cd "$(dirname "$0")" && pwd)"
OUT="$UI/dist/noethera-theme-setup.sh"
EOF_MARK="__NOETHERA_THEME_EOF__"
mkdir -p "$UI/dist"

rev="$(git -C "$UI" rev-parse --short HEAD 2>/dev/null || echo unknown)"
git -C "$UI" diff --quiet -- . 2>/dev/null || rev="$rev+uncommitted"

for f in "$UI"/bubbles.css "$UI"/themes/*.yaml; do
  if grep -q "$EOF_MARK" "$f"; then echo "Error: $f contains $EOF_MARK" >&2; exit 1; fi
done

{
  cat <<HEADER
#!/usr/bin/env bash
# Noethera Hermes theme (Claude style): warm Mono palette, chat bubbles, Open Sans, glass sidebar.
# One-file installer for a new device. Install Hermes first, then run:  bash noethera-theme-setup.sh
# Generated by noe-hermes/ui/build-portable.sh on $(date '+%Y-%m-%d %H:%M') from $rev. Do not edit by hand.
#
# What it does (safe to re-run; re-run after creating a new profile):
#   1. writes the skins (mono + default, with the Noethera CSS) into ~/.hermes and every profile
#      (existing files that differ are backed up to skins/.backup/)
#   2. activates the skin (display.skin = mono) in ~/.hermes and every profile
#   3. installs Open Sans if it is missing (Homebrew on macOS, else downloaded from Google Fonts)
#   4. sets the desktop sidebar translucency (glass) to the Noethera values
# Options:  --skin default   use the Nous palette instead of Mono (bubbles still apply)
#           --no-font        skip the font     --no-desktop   skip the translucency setting
HEADER
  cat <<'BODY'
set -euo pipefail

SKIN="mono"; DO_FONT=1; DO_DESKTOP=1
while [ $# -gt 0 ]; do
  case "$1" in
    --skin) SKIN="${2:?--skin needs a name}"; shift 2 ;;
    --no-font) DO_FONT=0; shift ;;
    --no-desktop) DO_DESKTOP=0; shift ;;
    -h|--help) sed -n '2,16p' "$0"; exit 0 ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
  esac
done

# Root Hermes home. HERMES_HOME may point at a profile inside a Hermes session, so use our own variable.
ROOT="${NOETHERA_HERMES_ROOT:-$HOME/.hermes}"
command -v hermes >/dev/null 2>&1 || {
  echo "Hermes is not installed. Install it first:"
  echo "  curl -fsSL https://hermes-agent.nousresearch.com/install.sh | bash"
  exit 1
}
[ -f "$ROOT/config.yaml" ] || { echo "No $ROOT/config.yaml yet. Run 'hermes setup' once, then run this again."; exit 1; }

PAYLOAD="$(mktemp -d)"
trap 'rm -rf "$PAYLOAD"' EXIT
mkdir -p "$PAYLOAD/themes"
BODY

  echo
  echo "# ---------- payload: bubbles.css ----------"
  echo "cat > \"\$PAYLOAD/bubbles.css\" <<'$EOF_MARK'"
  cat "$UI/bubbles.css"
  echo "$EOF_MARK"
  for theme in "$UI"/themes/*.yaml; do
    name="$(basename "$theme")"
    echo
    echo "# ---------- payload: themes/$name ----------"
    echo "cat > \"\$PAYLOAD/themes/$name\" <<'$EOF_MARK'"
    cat "$theme"
    echo "$EOF_MARK"
  done
  echo

  cat <<'BODY'
[ -f "$PAYLOAD/themes/$SKIN.yaml" ] || { echo "Unknown skin '$SKIN' (available: $(ls "$PAYLOAD/themes" | sed 's/\.yaml$//' | tr '\n' ' '))" >&2; exit 2; }

# 1. Skins into the root and every profile (the desktop reads the active profile's home).
build() { cat "$1"; printf '\ncustomCSS: |\n'; sed 's/^/  /' "$PAYLOAD/bubbles.css"; }
stamp="$(date +%Y%m%d-%H%M%S)"
homes=("$ROOT")
for p in "$ROOT"/profiles/*/; do [ -d "$p" ] && homes+=("${p%/}"); done
for home in "${homes[@]}"; do
  mkdir -p "$home/skins"
  for theme in "$PAYLOAD"/themes/*.yaml; do
    name="$(basename "$theme")"; target="$home/skins/$name"
    build "$theme" > "$PAYLOAD/built.yaml"
    if [ -f "$target" ] && ! cmp -s "$PAYLOAD/built.yaml" "$target"; then
      mkdir -p "$home/skins/.backup"; cp "$target" "$home/skins/.backup/$name.$stamp"
    fi
    cp "$PAYLOAD/built.yaml" "$target"; chmod 644 "$target"
  done
  rm -f "$home/skins/noethera.yaml"
done
echo "Skins installed in ${#homes[@]} Hermes home(s): $ROOT and $(( ${#homes[@]} - 1 )) profile(s)"

# 2. Activate the skin everywhere (hermes config set writes valid YAML; never hand-edit config.yaml).
for home in "${homes[@]}"; do
  [ -f "$home/config.yaml" ] || continue
  HERMES_HOME="$home" hermes config set display.skin "$SKIN" >/dev/null 2>&1 \
    && echo "  display.skin = $SKIN  ($home)" || echo "  Could not set the skin in $home; run: HERMES_HOME=$home hermes config set display.skin $SKIN"
done

# 3. Open Sans (bubbles.css uses the installed font, not the network).
if [ "$DO_FONT" = 1 ]; then
  case "$(uname -s)" in
    Darwin) fontdir="$HOME/Library/Fonts"; have() { compgen -G "$HOME/Library/Fonts/OpenSans*" >/dev/null || compgen -G "/Library/Fonts/OpenSans*" >/dev/null; } ;;
    *)      fontdir="$HOME/.local/share/fonts"; have() { fc-list 2>/dev/null | grep -qi "Open Sans"; } ;;
  esac
  if have; then
    echo "Open Sans already installed"
  elif [ "$(uname -s)" = Darwin ] && command -v brew >/dev/null 2>&1 && brew install --cask font-open-sans >/dev/null 2>&1; then
    echo "Open Sans installed (Homebrew)"
  else
    mkdir -p "$fontdir"
    base="https://github.com/google/fonts/raw/main/ofl/opensans"
    if curl -fsSL "$base/OpenSans%5Bwdth,wght%5D.ttf" -o "$fontdir/OpenSans[wdth,wght].ttf" \
       && curl -fsSL "$base/OpenSans-Italic%5Bwdth,wght%5D.ttf" -o "$fontdir/OpenSans-Italic[wdth,wght].ttf"; then
      command -v fc-cache >/dev/null 2>&1 && fc-cache -f "$fontdir" >/dev/null 2>&1 || true
      echo "Open Sans installed (Google Fonts) in $fontdir"
    else
      echo "Note: could not install Open Sans; the app falls back to the system font. Install it manually later."
    fi
  fi
fi

# 4. Desktop glass sidebar (stored by the app, not in the skin).
if [ "$DO_DESKTOP" = 1 ]; then
  case "$(uname -s)" in
    Darwin) appdir="${NOETHERA_APP_DIR:-$HOME/Library/Application Support/Hermes}" ;;
    *)      appdir="${NOETHERA_APP_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/Hermes}" ;;
  esac
  mkdir -p "$appdir"
  cat > "$appdir/translucency.json" <<'JSON'
{
  "intensity": 29,
  "fade": 0,
  "mode": "glass",
  "material": "header",
  "scope": "sidebar"
}
JSON
  echo "Desktop translucency set (glass sidebar)"
fi

echo
echo "Done. Quit and reopen the Hermes desktop app (Cmd+Q) to load the fonts and sidebar; the CLI/TUI repaint live."
echo "New profile later? Run this script again. Revert: hermes config set display.skin default"
BODY
} > "$OUT"

chmod 755 "$OUT"
bash -n "$OUT"
echo "Built $OUT ($rev, $(wc -c < "$OUT" | tr -d ' ') bytes)"
